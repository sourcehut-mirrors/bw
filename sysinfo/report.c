#if ! defined (_XOPEN_SOURCE)
#define _XOPEN_SOURCE 600
#endif

#include <locale.h>
#include <stddef.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <stdarg.h>
#include <string.h>
#include <inttypes.h>
#include <unistd.h>
#include <sys/resource.h>
#include <sys/utsname.h>
#include <math.h>
#include <fenv.h>

#define VERBOSE 1
#define SYSINFO_FAIL 127

int sysinfo(int verbose);

int main(int argc, char **argv)
{

    setlocale( LC_ALL, "C" );
    if ( sysinfo( VERBOSE ) == SYSINFO_FAIL ) {
        fprintf(stderr,"FAIL : sysinfo returns SYSINFO_FAIL\n");
        return EXIT_FAILURE;
    }

    return EXIT_SUCCESS;

}

